import assert from 'node:assert/strict';
import {sortRows,relativeAge,versionState} from '../plugins/context-observer/ui-state.mjs';
const rows=[{label:'No data',tokens:null,status:'unavailable'},{label:'Zero',tokens:0,status:'estimate'},{label:'Highest',tokens:120,status:'estimate'},{label:'Lowest',tokens:12,status:'estimate'}];
assert.deepEqual(sortRows(rows).map(x=>x.label),['Highest','Lowest','Zero','No data']);
assert.equal(rows[0].label,'No data');
assert.equal(relativeAge(null),'not recorded');
assert.equal(relativeAge(1000,31000),'30 s ago');
assert.equal(relativeAge(100000,1000),'just now');
assert.deepEqual(versionState('0.1.3',{runningVersion:'0.2.0',installedVersion:'0.2.1'}),{mismatch:true,pending:true});
assert.deepEqual(versionState('0.2.0',{runningVersion:'0.2.0',installedVersion:'0.2.0'}),{mismatch:false,pending:false});
console.log('Sorting, freshness and version comparisons: OK.');
